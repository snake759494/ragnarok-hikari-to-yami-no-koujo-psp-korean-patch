    spec = {}
    titles = ET + ['예비'] * 8 + ET2 + ['예비'] * 11
    for i, t in enumerate(titles):
        n = i + 1
        p = f'status/06/et{n:03d}.giz'
        if os.path.exists(os.path.join(CFI, p)): spec[p + '#0'] = label(p, t, 'et')
    for code, name in AREA.items():
        p = f'status/12/{code}.giz'
        if os.path.exists(os.path.join(CFI, p)): spec[p + '#0'] = label(p, name, 'area')
    spec['status/12/12_02b_01.giz#0'] = label('status/12/12_02b_01.giz', '연합국가 아우라의 영지', 'area')
    spec['status/12/12_02b_02.giz#0'] = label('status/12/12_02b_02.giz', '미혹의 숲', 'area')
    for k, t in WIN.items():
        p = f'status/12/win{k}.giz'
        if os.path.exists(os.path.join(CFI, p)): spec[p + '#0'] = label(p, t, 'cond')
    for k, t in LOSE.items():
        p = f'status/12/lose{k}.giz'
        if os.path.exists(os.path.join(CFI, p)): spec[p + '#0'] = label(p, t, 'cond')
