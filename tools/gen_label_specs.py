def bbox(path):
    im = gimpng.decode(open(os.path.join(CFI, path), 'rb').read())[0]
    return im.size, im.getbbox()


def label(path, text, style):
    (W, H), bb = bbox(path)
    x0, y0, x1, y1 = bb
    ops = [{'op': 'erase', 'rect': [0, 0, W, H], 'mode': 'clear'}]
    if style == 'et':
        cx = (x0 + x1) // 2; w = min(W - 4, max(x1 - x0 + 40, 200)); x = max(2, min(W - 2 - w, cx - w // 2))
        ops.append({'op': 'text', 'rect': [x, 1, w, H - 2], 'text': text, 'size': 15, 'font': 'eb',
                    'color': [253, 253, 232, 255], 'outline': [66, 34, 26, 240], 'ow': 1,
                    'shadow': [40, 20, 15, 160]})
    elif style == 'area':
        ops.append({'op': 'text', 'rect': [4, 3, W - 6, H - 22], 'text': text, 'size': 40, 'font': 'hv', 'align': 'r',
                    'gradient': [[232, 244, 200, 255], [150, 212, 124, 255]], 'outline': [95, 95, 63, 255], 'ow': 1,
                    'shadow': [40, 40, 25, 170]})
    else:
        nl = text.count('\n') + 1
        cx = (x0 + x1) // 2; half = min(cx - 2, W - 2 - cx)
        ops.append({'op': 'text', 'rect': [cx - half, max(0, (y0 + y1) // 2 - 9 * nl), 2 * half, 18 * nl], 'text': text,
                    'size': 13, 'font': 'bd', 'color': [254, 254, 254, 255], 'shadow': [20, 20, 30, 170], 'lh': 1.05,
                    'align': 'c'})
    return ops


